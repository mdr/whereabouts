// Writes <name>.module.css.d.ts beside every CSS module, listing the classes
// it exports, so a class missing from its CSS fails the typecheck.
//
// Usage, from packages/client: node scripts/css-module-types.mjs
// Also used by the dev server (vite.config.ts), which keeps them current.
import { existsSync, globSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { pathToFileURL } from "node:url"
import { transform } from "lightningcss"

const SOURCE = "src/**/*.module.css"
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/

/** The declaration for a CSS module's source, from the same transform as the build. */
function declarationFor(filename, css) {
  const { exports } = transform({
    filename,
    code: Buffer.from(css),
    cssModules: true,
    drafts: { customMedia: true }
  })
  const members = Object.keys(exports ?? {})
    .sort()
    .map((name) => `  readonly ${IDENTIFIER.test(name) ? name : JSON.stringify(name)}: string`)
  return `// Generated by scripts/css-module-types.mjs.\ndeclare const styles: {\n${members.join("\n")}\n}\nexport default styles\n`
}

/** Writes one module's declaration, unless it is already current. */
export function writeDeclaration(file) {
  const target = `${file}.d.ts`
  const text = declarationFor(file, readFileSync(file, "utf8"))
  if (!existsSync(target) || readFileSync(target, "utf8") !== text) writeFileSync(target, text)
}

export function generateAll() {
  const modules = new Set(globSync(SOURCE))
  for (const file of modules) writeDeclaration(file)
  for (const declaration of globSync(`${SOURCE}.d.ts`)) {
    if (!modules.has(declaration.slice(0, -".d.ts".length))) rmSync(declaration)
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) generateAll()
